import { describe, expect, it } from 'vitest';
import { parseGradleLockfile } from './gradle-lockfile.js';

describe('parseGradleLockfile', () => {
  it('skips comment lines that mimic the coordinate pattern', () => {
    const text = [
      '# com.example:fake:9.9.9=runtimeClasspath',
      'com.google.guava:guava:31.1-jre=compileClasspath',
    ].join('\n');
    const index = parseGradleLockfile(text);
    expect(index.has('com.example:fake')).toBe(false);
    expect(index.get('com.google.guava:guava')).toBe('31.1-jre');
  });

  it('skips empty= configuration markers', () => {
    const text = [
      'empty=annotationProcessor',
      'org.slf4j:slf4j-api:2.0.9=runtimeClasspath',
    ].join('\n');
    const index = parseGradleLockfile(text);
    expect(index.size).toBe(1);
    expect(index.get('org.slf4j:slf4j-api')).toBe('2.0.9');
  });

  it('keeps only real coordinates in insertion order', () => {
    const text = [
      '# generated by Gradle',
      'com.google.guava:guava:31.1-jre=compileClasspath',
      'empty=annotationProcessor',
      '# com.example:fake:9.9.9=runtimeClasspath',
      'org.slf4j:slf4j-api:2.0.9=runtimeClasspath',
      '',
    ].join('\n');
    const index = parseGradleLockfile(text);
    expect([...index.keys()]).toEqual([
      'com.google.guava:guava',
      'org.slf4j:slf4j-api',
    ]);
    expect(index.get('com.google.guava:guava')).toBe('31.1-jre');
    expect(index.get('org.slf4j:slf4j-api')).toBe('2.0.9');
  });

  it('returns an empty map for empty or comment-only input', () => {
    expect(parseGradleLockfile('').size).toBe(0);
    expect(parseGradleLockfile('# only comments\nempty=annotationProcessor\n').size).toBe(0);
  });
});
